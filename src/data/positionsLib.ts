function 短(city: string): string {
  return city.slice(-1)
}

function 副职(d: Dept): string {
  if (d.类别 === '党委') {
    if (/组织部$|宣传部$|统一战线工作部$/.test(d.名)) return `${d.名}副部长`
    if (/政法委员会$|纪律检查委员会$/.test(d.名)) return `${d.名}副书记`
    if (/党校/.test(d.名)) return `${d.名}副校长`
    if (/老干部局$/.test(d.名)) return `${d.名}副局长`
    return `${d.名}副主任`
  }
  if (d.类别 === '群团') return /共青团/.test(d.名) ? `${d.名}副书记` : `${d.名}副主席`
  if (d.类别 === '人大政协') return `${d.名}副主任`
  return /委员会$/.test(d.名) ? `${d.名}副主任` : `${d.名}副局长`
}

/* 县区正科：常委部门给“副职”，非常委党委部门给正职；党校特殊 */
function 县区正职(d: Dept): string {
  if (d.类别 === '党委') {
    if (/办公室$|组织部$|宣传部$|统一战线工作部$|政法委员会$|纪律检查委员会$/.test(d.名)) return 副职(d)
    if (/党校/.test(d.名)) return `${d.名}常务副校长`
    if (/机关工作委员会$/.test(d.名)) return `${d.名}副书记`
    if (/老干部局$/.test(d.名)) return `${d.名}局长`
    return `${d.名}主任`
  }
  return 正职(d)
}

function 正职(d: Dept): string {
  if (d.类别 === '党委') {
    if (/组织部$|宣传部$|统一战线工作部$/.test(d.名)) return `${d.名}部长`
    if (/政法委员会$|纪律检查委员会$/.test(d.名)) return `${d.名}书记`
    if (/党校/.test(d.名)) return `${d.名}校长`
    if (/老干部局$/.test(d.名)) return `${d.名}局长`
    return `${d.名}主任`
  }
  if (d.类别 === '群团') return /共青团/.test(d.名) ? `${d.名}书记` : `${d.名}主席`
  if (d.类别 === '人大政协') return `${d.名}主任`
  return /委员会$/.test(d.名) ? `${d.名}主任` : `${d.名}局长`
}

function 党委部门(平台: PlatformName, city: string): Dept[] {
  const p = 平台 === '省级' ? '省' : `${city}委`
  const 纪委 = 平台 === '省级' ? '省纪律检查委员会' : 平台 === '市级' ? `${city}纪委` : `${city}纪律检查委员会`
  const list: [string, 类别][] = [
    [`${p}办公室`, '党委'], [纪委, '党委'], [`${p}组织部`, '党委'], [`${p}宣传部`, '党委'],
    [`${p}统一战线工作部`, '党委'], [`${p}政法委员会`, '党委'], [`${p}政策研究室`, '党委'],
    [`${p}机构编制委员会办公室`, '党委'], [`${p}直属机关工作委员会`, '党委'],
    [`${p}巡察工作领导小组办公室`, '党委'], [`${p}党校（行政学院）`, '党委'],
    [`${p}党史和地方志研究室`, '党委'], [`${p}网络安全和信息化委员会办公室`, '党委'],
    [`${p}台湾工作办公室`, '党委'], [`${p}老干部局`, '党委'],
  ]
  return list.map(([名, 类]) => ({ 名, 类别: 类 }))
}

function 政府部门(平台: PlatformName, city: string): Dept[] {
  const list = 平台 === '县级' || 平台 === '区级' ? 政府县区 : 平台 === '市级' ? 政府市级 : 政府省级
  return list.map((名) => ({ 名: 平台 === '省级' ? 名 : `${city}${名}`, 类别: '政府' as 类别 }))
}

function 群团部门(平台: PlatformName, city: string): Dept[] {
  const out: Dept[] = []
  for (const 团 of 群团词) {
    const 名 = 团 === '共青团'
      ? (平台 === '省级' ? '共青团省委' : `共青团${city}委`)
      : 团 === '总工会'
        ? (平台 === '省级' ? '省总工会' : `${city}总工会`)
        : `${平台 === '省级' ? '省' : city}${团}`
    out.push({ 名, 类别: '群团' })
  }
  return out
}

function 人大政协部门(平台: PlatformName, city: string): Dept[] {
  const out: Dept[] = []
  const 人大 = 平台 === '省级' ? '省人大常委会' : `${city}人大常委会`
  const 政协 = 平台 === '省级' ? '省政协' : `${city}政协`
  out.push({ 名: `${人大}办公室`, 类别: '人大政协' })
  for (const 委 of 县区人大委) out.push({ 名: `${人大}${委}`, 类别: '人大政协' })
  out.push({ 名: `${政协}办公室`, 类别: '人大政协' })
  for (const 委 of 政协专委) out.push({ 名: `${政协}${委}`, 类别: '人大政协' })
  return out
}

