export function 职业机构(职业: Job, 平台序: number): string[] {
  if (职业 === '公务员') return []
  const def = CAREERS[职业 as Exclude<Job, '公务员'>]
  if (!def) return []
  return (def.机构[平台序] || []).slice()
}
