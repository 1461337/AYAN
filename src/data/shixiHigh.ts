function 生成层级(省部: boolean, 职级范围: [number, number]): ShixiItem[] {
  const 通用情景s = 省部 ? 省情景 : 厅情景
  return 领域s.map((d, di) => {
    const 情景s = d.情景 || 通用情景s
    const qs: ShixiQuestion[] = 情景s.map((f, si) => {
      const L = 省部 ? (si % 2 ? '全省' : '全国') : (si % 2 ? '全省' : '全市')
      const q = f(L, d.名) + 定语[(di + si) % 定语.length] + '？'
      const 正 = d.正确[(di + si) % d.正确.length]
      const 模 = 模糊池[d.类][(di + si) % 模糊池[d.类].length]
      const 错 = 错误池[d.类][(di + si) % 错误池[d.类].length]
      const 正确收益: Effect = 省部
        ? { 政绩: 42 + si, 能力: 3, 道德: 2, 声望: 5, 上司: 3 }
        : { 政绩: 30 + si, 能力: 2, 道德: 2, 声望: 4, 上司: 2 }
      return {
        q,
        a: [
          { 判: '正确', 文: 正, e: 正确收益, fb: `你${正}。问题逐步化解，相关做法得到上级肯定。` },
          { 判: '模糊', 文: 模, e: { 政绩: 省部 ? 14 : 9 }, fb: `你${模}。事情暂时压住了，但根子还在。` },
          { 判: '错误', 文: 错, e: { 政绩: 省部 ? -14 : -10, 道德: -5, 声望: -5, 廉政风险: 省部 ? 14 : 10 }, fb: `你${错}。问题没有解决，还引发了新的反映。` },
        ],
      }
    })
    const asks = [[...qs], [...qs], [...qs], [...qs], [...qs]]
    return {
      名: `${d.名}·${省部 ? '省部' : '厅局'}`,
      desc: `${省部 ? '全省' : '分管领域'}${d.名}的统筹与决策`,
      e: { 政绩: 省部 ? 30 : 22 },
      asks,
      职级范围,
      条线: d.条线,
    }
  })
}

