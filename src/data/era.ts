export interface 年度项目 {
  名: string
  描述: string
  进度: number
  阶段: string
}

export function 年度项目(year: number, 城市: string, city: GameState['city']): 年度项目[] {
  const 短 = 城市.replace(/[市县委区镇乡]/g, '')
  const start = (year * 3) % 项目池.length
  return [0, 1, 2].map((i) => {
    const t = 项目池[(start + i * 4) % 项目池.length]
    const 进度 = city[t.指标]
    const 阶段 = 进度 >= 70 ? '加速推进' : 进度 >= 55 ? '稳步实施' : 进度 >= 45 ? '前期准备' : '进度滞后'
    return { 名: `${短}${t.名}`, 描述: t.文案, 进度, 阶段 }
  })
}
