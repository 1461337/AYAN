export function validateName(raw: string): string | null {
  const n = (raw || '').trim()
  if (!n) return '请填写姓名'
  if (/\s/.test(n)) return '姓名不能包含空格'
  if (/[a-zA-Z0-9]/.test(n)) return '姓名不能包含字母或数字'
  if (!/^[\u4e00-\u9fa5]+$/.test(n)) return '姓名只能使用汉字'
  if (n.length < 2) return '姓名至少为 2 个汉字'
  if (n.length > 4) return '姓名最多为 4 个汉字'
  for (const s of 敏感姓) if (n.includes(s)) return '该姓名涉及敏感人物，请重新填写'
  for (const s of 不当称谓) if (n.includes(s)) return '姓名不得使用职务或不当称谓'
  for (const b of 违禁) if (n.includes(b)) return '该姓名不符合公序良俗，请重新填写'
  const fx = 复姓.find((c) => n.startsWith(c))
  if (fx) {
    if (n.length < fx.length + 1) return '复姓之后请至少再写一个字'
  } else if (!单姓.includes(n[0])) return '姓氏“' + n[0] + '”不常见，请使用常见姓氏'
  return null
}

