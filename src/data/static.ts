export function mkLadder(names: string[], base: number): RankDef[] {
  return names.map((n, i) => ({
    名: n, 月薪: Math.round(base * Math.pow(1.5, i)), 最低年: i === 0 ? 3 : (i >= 4 ? 3 : 2),
    门槛: { 政绩: Math.round(150 * Math.pow(2.0, i)), 能力: Math.min(95, 45 + i * 6), 道德: 55, 上司: Math.min(95, 42 + i * 6) },
    例: [n + '（综合）', n + '（业务）', n + '（市场）', n + '（技术）', n + '（行政）', n + '（财务）'],
  }))
}

