export function npcTick(g: GameState): void {
  for (const n of g.npcs) {
    n.年龄++
    if (n.年龄 >= 62 && chance(0.22)) {
      const 旧名 = n.姓名
      let npc = makeNpc(g, n.id)
      let guard = 0
      while (guard++ < 20 && (npc.姓名 === 旧名 || g.npcs.some((o) => o.id !== n.id && o.姓名 === npc.姓名))) {
        npc = makeNpc(g, n.id)
      }
      Object.assign(n, npc)
      g.log.unshift({ t: `${g.date.y}年`, h: '人脉更替', kind: '', d: `${旧名}到龄退居二线，${n.姓名}接替了他的位置。关系网总要跟着年份更新。` })
      continue
    }
    if (chance(0.5)) n.好感度 = clamp(n.好感度 + rnd(-3, 2), 0, 100)
    if (chance(0.35)) n.信任 = clamp(n.信任 + rnd(-2, 2), -100, 100)
    if (chance(0.16)) {
      pick<() => void>([
        () => {
          n.身份 = n.身份.replace(/副处长|处长/, '处长')
          n.信任 = clamp(n.信任 + 3, -100, 100)
          g.log.unshift({ t: `${g.date.y}年`, h: `${n.姓名} 提任`, kind: '', d: `${n.姓名}被提任为${pick(['处长', '调研员', '副局长', '党委委员'])}。你没有出力，也没有反对。` })
        },
        () => { g.log.unshift({ t: `${g.date.y}年`, h: `${n.姓名} 调离`, kind: '', d: `${n.姓名}调往${pick(['省厅', '另一个区', '开发区管委会', '直辖市挂职'])}。此后再见面，身份已经不同。` }) },
        () => {
          n.信任 = clamp(n.信任 - rnd(3, 10), -100, 100)
          n.利益 = clamp(n.利益 + rnd(5, 15), -100, 100)
          g.log.unshift({ t: `${g.date.y}年`, h: `${n.姓名} 的立场变了`, kind: 'bad', d: `因为一次资源分配，${n.姓名}在会上的态度和以前不一样了。关系不会因为一句话永久固定。` })
        },
        () => {
          n.信任 = clamp(n.信任 + rnd(3, 8), -100, 100)
          g.log.unshift({ t: `${g.date.y}年`, h: `${n.姓名} 帮了你一次`, kind: 'good', d: `你不在场的一个会上，${n.姓名}替你说了话。你是后来才听说的。` })
        },
      ])()
    }
  }
  if (g.log.length > 90) g.log.length = 90
}

export function cityTick(g: GameState): void {
  const keys = Object.keys(g.city) as Array<keyof GameState['city']>
  for (const k of keys) if (chance(0.5)) g.city[k] = clamp(g.city[k] + rnd(-4, 4), 10, 95)
  g.market = g.market || { 房价: 1 }
  const drift = ((g.city.房地产 - 50) / 100) * 0.03 + rnd(-18, 22) / 1000
  g.market.房价 = Math.max(0.45, g.market.房价 * (1 + drift))
  g.assets.房产.forEach((x) => { if (x.购入价) x.市值 = Math.round(x.购入价 * g.market.房价) })
  g.assets.车辆.forEach((v) => {
    const 车龄 = Math.max(0, g.date.y - (v.购入年 || g.date.y))
    v.市值 = Math.round((v.总价 || 0) * (车龄 >= 15 ? 0.05 : Math.pow(0.85, 车龄)))
  })
}
