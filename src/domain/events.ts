/* 近期出现过的事件不再连续出现，保证突发事件随机且不重样 */
export function 近期去重(g: GameState, pool: GameEvent[]): GameEvent[] {
  const 近 = g._近期事件 || []
  const 新 = pool.filter((ev) => !近.includes(ev.标题))
  return 新.length ? 新 : pool
}

export function 记录事件(g: GameState, ev: GameEvent): void {
  g._近期事件 = [...(g._近期事件 || []).filter((x) => x !== ev.标题), ev.标题].slice(-10)
}

