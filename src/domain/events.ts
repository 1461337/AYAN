/* 事件适用条件：职级、条线、家庭、临近退休等 */
export function 事件可用(g: GameState, ev: GameEvent): boolean {
  const m = ev.门槛
  if (!m) return true
  if (m.最低职级 != null && g.rankIdx < m.最低职级) return false
  if (m.最高职级 != null && g.rankIdx > m.最高职级) return false
  if (m.需配偶 && !g.family.配偶) return false
  if (m.需子女 && !g.family.子女.length) return false
  if (m.需房产 && !g.assets.房产.length) return false
  if (m.需临近退休 && g.p.年龄 < retireAge(g) - 5) return false
  if (m.条线 && m.条线.length) {
    const 条 = 条线Of(g.positions[0] && g.positions[0].岗位)
    if (!m.条线.includes(条)) return false
  }
  return true
}

