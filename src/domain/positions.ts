export function 本地职位(平台: PlatformName, idx: number, 城市: string): LocalPos[] {
  switch (平台) {
    case '乡镇级': return 乡镇(城市, idx)
    case '县级':
    case '区级': return 县区(城市, idx)
    case '市级': return 市级(城市, idx)
    case '省级': return 省级(idx)
    default: return []
  }
}

const 上级平台表: Partial<Record<PlatformName, PlatformName>> = {
  '乡镇级': '县级',
  '县级': '市级',
  '区级': '市级',
  '市级': '省级',
}

export interface PoolPos {
  名: string
  本地: boolean
}

/* 本地职位优先，少量上级平台岗位代表上调机会 */
export function 晋升职位池(g: GameState, idx: number): PoolPos[] {
  const 平台 = g.p.平台
  const 本地 = 本地职位(平台, idx, g.p.城市).map((p) => ({ 名: p.名, 本地: true }))
  const 上级 = 上级平台表[平台]
  let 外地: PoolPos[] = []
  if (上级) {
    const 上城 = pick(平台表[上级].城市)
    const pool = 本地职位(上级, idx, 上城).map((p) => ({ 名: p.名, 本地: false }))
    const keep = Math.max(2, Math.min(5, Math.ceil(pool.length * 0.3)))
    外地 = shuffle(pool).slice(0, keep)
  }
  return 本地.concat(外地)
}
