function 公务员职位池(g: GameState, idx: number): PoolPos[] {
  const 现平台 = g.p.平台
  const 现序 = 平台序[现平台]
  const 上限 = 本地最高[现序]
  const out: PoolPos[] = []
  if (idx <= 上限) {
    const 本地 = 政治本地职位(现平台, idx, g.p.城市).map((p) => ({
      名: p.名, 序号: 现序, 本地: true, 城市: g.p.城市, 二线: p.二线,
    }))
    out.push(...本地)
    const 同城 = 平台表[现平台].城市.filter((c) => c !== g.p.城市)
    for (const c of shuffle(同城).slice(0, 3)) {
      out.push(...政治本地职位(现平台, idx, c).map((p) => ({ 名: p.名, 序号: 现序, 本地: false, 城市: c, 二线: p.二线 })))
    }
  } else {
    // 一次晋升最多上跨一级平台；若该平台没有对应职级岗位，则继续上溯（兼容异常状态）
    let 目标 = Math.min(3, 现序 + 1)
    while (目标 < 3 && 政治本地职位(序平台[目标], idx, g.p.城市).length === 0) 目标++
    const 城市s = shuffle(平台表[序平台[目标]].城市)
    for (const c of 城市s.slice(0, 2)) {
      out.push(...政治本地职位(序平台[目标], idx, c).map((p) => ({ 名: p.名, 序号: 目标, 本地: false, 城市: c, 二线: p.二线 })))
    }
  }
  return 补齐(out)
}

function 职业职位池(g: GameState, idx: number): PoolPos[] {
  const 职业 = g.p.职业
  const 现序 = 平台序[g.p.平台]
  const 上限 = 职业最高[现序]
  const L = ladderName(职业, idx)
  if (!L) return []
  const out: PoolPos[] = []
  if (idx <= 上限) {
    out.push(...职业本层(职业, 现序, L).map((p) => ({ ...p, 本地: true })))
  } else {
    // 一次晋升最多上跨一级平台
    let 目标 = Math.min(3, 现序 + 1)
    while (目标 < 3 && 职业本层(职业, 目标, L).length === 0) 目标++
    out.push(...职业本层(职业, 目标, L))
  }
  return 补齐(out)
}

function ladderName(职业: Job, idx: number): string {
  if (职业 === '公务员') return 职务阶梯[idx] ? 职务阶梯[idx].名 : ''
  const L = LADDER_NAMES[职业]
  return L && L[idx] ? L[idx] : ''
}

const LADDER_NAMES: Record<string, string[]> = {
  '事业单位': ['科员', '副科长', '科长', '副处长', '处长', '副主任'],
  '国企': ['职员', '业务主管', '部门副经理', '部门经理', '副总经理', '总经理', '集团副总经理'],
  '企业': ['业务员', '业务主管', '部门经理', '总监', '副总经理', '总经理'],
  '记者': ['见习记者', '记者', '资深记者', '部门副主任', '部门主任', '副总编辑', '总编辑'],
  '教师': ['二级教师', '一级教师', '高级教师', '教务处副主任', '副校长', '校长'],
  '医生': ['住院医师', '主治医师', '副主任医师', '主任医师', '科室副主任', '科室主任'],
}

function 补齐(pool: PoolPos[]): PoolPos[] {
  const seen = new Set<string>()
  return pool.filter((p) => {
    if (seen.has(p.名)) return false
    seen.add(p.名)
    return true
  })
}

export function 晋升职位池(g: GameState, idx: number): PoolPos[] {
  return g.p.职业 === '公务员' ? 公务员职位池(g, idx) : 职业职位池(g, idx)
}

/* 由岗位名推断所属机构（用于晋升后同步单位） */
export function 机构Of(名: string, 城市: string, 平台: PlatformName, 职业: Job): string {
  if (职业 !== '公务员') {
    const m = 名.match(/^(.+?(?:中心|学院|学校|中学|小学|医院|卫生院|日报社|电视台|记者站|融媒体中心|集团|公司|企业|研究院|设计院|图书馆|博物馆|文化馆|服务中心|站))/)
    return m ? m[1] : 名
  }
  const 短 = 城市.slice(-1)
  const 条 = 条线OfLocal(名)
  const 省 = 平台 === '省级'
  switch (条) {
    case '纪检': return 省 ? '省纪委监委' : `${城市}纪委监委`
    case '法院': return 省 ? '省高级人民法院' : `${城市}人民法院`
    case '检察': return 省 ? '省人民检察院' : `${城市}人民检察院`
    case '公安': return 省 ? '省公安厅' : `${城市}公安局`
    case '司法': return 省 ? '省司法厅' : `${城市}司法局`
    case '组工': return `${城市}委组织部`
    case '宣传': return `${城市}委宣传部`
    case '统战': return `${城市}委统战部`
    case '政法': return `${城市}委政法委`
    case '财政': return 省 ? '省财政厅' : `${城市}财政局`
    case '发改': return `${城市}发展和改革${省 ? '委员会' : '局'}`
    case '教育': return 省 ? '省教育厅' : `${城市}教育局`
    case '住建': return 省 ? '省住房和城乡建设厅' : `${城市}住房和城乡建设局`
    case '卫健': return `${城市}卫生健康${省 ? '委员会' : '局'}`
    case '交通': return 省 ? '省交通运输厅' : `${城市}交通运输局`
    case '工信': return 省 ? '省工业和信息化厅' : `${城市}工业和信息化局`
    case '农业': return 省 ? '省农业农村厅' : `${城市}农业农村局`
    case '生态': return 省 ? '省生态环境厅' : `${城市}生态环境局`
    case '审计': return 省 ? '省审计厅' : `${城市}审计局`
    case '市场监管': return 省 ? '省市场监督管理局' : `${城市}市场监督管理局`
    case '自然资源': return 省 ? '省自然资源厅' : `${城市}自然资源局`
    case '人大政协': return /政协/.test(名) ? `${城市}政协` : `${城市}人大常委会`
    case '主官': return /书记|副书记/.test(名) ? `${城市}委` : `${城市}${短}政府`
    default: return `${城市}政府办公室`
  }
}

function 条线OfLocal(名: string): string {
  if (/人大常委会|政协/.test(名)) return '人大政协'
  if (/县委书记|区委书记|市委书记|省委书记|县长|区长|市长|省长|乡长|镇长|副乡长|副镇长|副县长|副区长|副市长|副省长|[乡镇]党委书记/.test(名)) return '主官'
  const 表: [string, RegExp][] = [
    ['纪检', /纪委|纪检|监委/], ['法院', /法院/], ['检察', /检察/], ['公安', /公安/], ['司法', /司法/],
    ['政法', /政法委/], ['组工', /组织/], ['宣传', /宣传|文旅/], ['统战', /统战/], ['财政', /财政/],
    ['住建', /住房和城乡建设/], ['发改', /发展和改革/], ['教育', /教育/], ['卫健', /卫生健康/],
    ['交通', /交通/], ['工信', /工业和信息化/], ['农业', /农业农村/], ['生态', /生态环境/],
    ['审计', /审计/], ['市场监管', /市场监督管理/], ['自然资源', /自然资源|规划/],
  ]
  for (const [k, re] of 表) if (re.test(名)) return k
  return '综合'
}

